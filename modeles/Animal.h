#ifndef ANIMAL_H
#define ANIMAL_H

#include <vector>
#include "Mangeoire.h"

class Animal; 

/**
 * @struct AnimalArgs
 * @brief Structure encapsulating the arguments passed to the animal thread.
 */
struct AnimalArgs {
    Animal* animal;                     ///< Pointer to the animal instance.
    std::vector<Mangeoire>* mangeoires; ///< Pointer to the vector of feeders for the animal to access.
};

/**
 * @brief Represents an animal (Squirrel or Cardinal) in the simulation.
 * @details Manages the animal's life cycle, its food consumption,
 * and its digestion state at each clock tick.
 */
class Animal
{
private:
    /* data */
    int id;           ///< Unique animal identifier
    char type;        ///< 'E' for Squirrel (Écureuil), 'C' for Cardinal
    volatile bool alive;       ///< Life state (true = alive, false = dead)
    int portion;      ///< Amount of seeds consumed per meal
    int digest_time;  ///< Digestion duration required after a meal (in ticks)
    int digest_timer; ///< Internal countdown timer for digestion

    /* statistics data */
    int total_eaten;     ///< Total number of meals successfully consumed
    int meals_count;     ///< Total number of meal attempts (successful or not)

public:
    /**
     * @brief Constructor for the Animal class.
     * @param id The unique identifier generated by the parser.
     * @param type The species type ('E' or 'C').
     * @param portion The number of seeds required per meal.
     * @param digest_time The digestion duration.
     */
    Animal(int id, char type, int portion, int digest_time);

    /**
     * @brief Destructor for the Animal class.
     */
    ~Animal();

    /**
     * @brief Attempts to feed the animal on a randomly chosen feeder.
     * @details The animal selects a feeder at random. If enough seeds are available,
     * it eats and starts its digestion countdown. Otherwise, it dies instantly.
     * @param feeders Reference to the vector containing all feeders in the simulation.
     */
    void consume(std::vector<Mangeoire> &feeders);

    /**
     * @brief Animal thread entry function (static method).
     * @details Aligns the animal's execution to the clock pulses via a conditional variable (`pthread_cond_wait`). 
     * As long as the simulation is active and the animal is alive, it executes its `consume()` method.
     * @param arg Opaque pointer to an AnimalArgs structure.
     * @return nullptr at the end of thread execution.
     */
    static void* thread_func(void* arg);

    /**
     * @brief Checks if the animal is still alive.
     * @return true if the animal is alive, false if it died of starvation.
     */
    bool isAlive() const;

    /**
     * @brief Gets the unique identifier of the animal.
     * @return The animal's ID.
     */
    int getId() const;

    /**
     * @brief Gets the species type of the animal ('E' or 'C').
     * @return The character representing the species.
     */
    char getType() const;

    /**
     * @brief Gets the portion size required by the animal.
     * @return The number of seeds per meal.
     */
    int getPortion() const;

    /**
     * @brief Gets the total digestion time of the animal.
     * @return The number of ticks required to digest.
     */
    int getDigestTime() const;

    /**
     * @brief Gets the total number of meals successfully consumed by the animal.
     * @return The count of successful meals.
     */
    int getTotalEaten() const;

    /**
     * @brief Gets the total number of meal attempts made by the animal.
     * @return The count of meal attempts.
     */
    int getMealsCount() const;

};

#endif